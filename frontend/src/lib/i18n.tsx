const BUILTIN_DICTS: Record<string, Dict> = {
  en,
  es,
  fr,
  de,
  it,
  pt,
  ja,
  zh,
  ar,
  hi,
  tr,
};

export interface CustomLang {
  name: string;
  dict: Dict;
}

interface I18nCtx {
  lang: string;
  setLang: (code: string) => void;
  t: (key: string) => string;
  languages: { code: string; name: string; nativeName: string; flag: string; builtin: boolean }[];
  allWorldLanguages: LanguageMeta[];
  addLanguage: (code: string, name: string, dict: Dict) => void;
  removeLanguage: (code: string) => void;
  templateJson: () => string;
}

const Ctx = createContext<I18nCtx | null>(null);
const LS_LANG = 'norynt_crm_lang';
const LS_CUSTOM = 'norynt_crm_custom_langs';

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState('en');
  const [custom, setCustom] = useState<Record<string, CustomLang>>({});

  useEffect(() => {
    try {
      const c = JSON.parse(localStorage.getItem(LS_CUSTOM) || '{}');
      if (c && typeof c === 'object') setCustom(c);
    } catch {
      /* ignore */
    }
    const l = localStorage.getItem(LS_LANG);
    if (l) setLangState(l);
    else setLangState('en');
  }, []);

  const setLang = useCallback((code: string) => {
    setLangState(code);
    try {
      localStorage.setItem(LS_LANG, code);
      // Update HTML lang attribute dynamically
      if (typeof document !== 'undefined') {
        document.documentElement.lang = code;
      }
    } catch {
      /* ignore */
    }
  }, []);

  const dict = useMemo<Dict>(
    () => BUILTIN_DICTS[lang] ?? custom[lang]?.dict ?? en,
    [lang, custom],
  );

  // Triple-layer Fallback: Active Dict -> Lowercase Dict -> English Standard Dict -> Lowercase English -> Key
  const t = useCallback(
    (key: string) =>
      dict[key] ??
      dict[key.toLowerCase()] ??
      en[key] ??
      en[key.toLowerCase()] ??
      key,
    [dict],
  );

  const persistCustom = (next: Record<string, CustomLang>) => {
    try {
      localStorage.setItem(LS_CUSTOM, JSON.stringify(next));
    } catch {
      /* ignore */
    }
  };

  const addLanguage = useCallback(
    (code: string, name: string, d: Dict) => {
      setCustom((prev) => {
        const next = { ...prev, [code]: { name, dict: d } };
        persistCustom(next);
        return next;
      });
    },
    [],
  );

  const removeLanguage = useCallback(
    (code: string) => {
      setCustom((prev) => {
        const next = { ...prev };
        delete next[code];
        persistCustom(next);
        return next;
      });
      setLangState((cur) => {
        if (cur !== code) return cur;
        try {
          localStorage.setItem(LS_LANG, 'en');
        } catch {
          /* ignore */
        }
        return 'en';
      });
    },
    [],
  );

  const languages = useMemo(
    () => [
      ...WORLD_LANGUAGES.map((wl) => ({
        code: wl.code,
        name: wl.name,
        nativeName: wl.nativeName,
        flag: wl.flag,
        builtin: true,
      })),
      ...Object.entries(custom).map(([code, v]) => ({
        code,
        name: v.name,
        nativeName: v.name,
        flag: '🌐',
        builtin: false,
      })),
    ],
    [custom],
  );

  const templateJson = useCallback(() => JSON.stringify(en, null, 2), []);

  const value: I18nCtx = {
    lang,
    setLang,
    t,
    languages,
    allWorldLanguages: WORLD_LANGUAGES,
    addLanguage,
    removeLanguage,
    templateJson,
  };

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18nCtx {
  const c = useContext(Ctx);
  if (!c) throw new Error('useI18n must be used within I18nProvider');
  return c;
}
